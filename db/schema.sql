-- NMC Timewriting System - database schema (PostgreSQL 14 or later)
--
-- Schema version (the row in schema_info). The app refuses to start on a database with a lower number (see REQUIRED_SCHEMA in
-- app/nmc/core.py), so raise both together whenever an older database could no longer work with the app.
--   27: hours are approved by the person's line manager (or the approver named on their record, when someone else makes more sense): approval is per
--       person, not per client and scope, so client approvers and secondary approvers are gone. A person's default location, contracted hours per week
--       and approver are held on their record, and employment type is Staff, Contractor - LTD or Contractor - PAYE. The overtime flag is no longer used
--       (the column stays, always 0); v_weekly_hours gives each person's hours per week against their contracted hours, to work out overtime later.
--   26: the database moved from SQLite to PostgreSQL. Same tables and rules; the rules (triggers) are PL/pgSQL functions, dates stay as
--       yyyy-mm-dd text, and an email is kept in lower case. The SQLite schema (version 25) is in the backup db folder and in git history.
--   25: changes to people are recorded in user_audit.   24: people who do not write time (books_time = 0), such as directors.
--   23: people carry the Microsoft account they sign in with (email, Entra object id).
--   22: the offshore allowance is per night spent offshore and worked out from the hours (no claims, no allowance approvals).
--   Earlier: CTR sheet fields, line managers, budgets from P6, per-client main approvers with scope approvers, a 24 hour day cap,
--   append-only audit, rates and budgets, locations and overtime, reopening by a cost controller.
--
-- Create the database with the plain "C" collation so names sort the way they always have here (by character code, capitals first):
--   CREATE DATABASE nmc TEMPLATE template0 ENCODING 'UTF8' LC_COLLATE 'C' LC_CTYPE 'C';
-- Everything works without it, only the order of some lists differs.

CREATE TABLE schema_info (
    id      INTEGER PRIMARY KEY CHECK (id = 1),
    version INTEGER NOT NULL
);
INSERT INTO schema_info (id, version) VALUES (1, 27);

