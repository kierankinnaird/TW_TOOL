-- The Monday of the week a date falls in, as yyyy-mm-dd text. Weeks run Monday to Sunday and are named by their Monday.
CREATE FUNCTION monday_of(d TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE AS
$$ SELECT to_char(date_trunc('week', d::date), 'YYYY-MM-DD') $$;

-- The current time as text, in UTC: yyyy-mm-dd hh:mm:ss
CREATE FUNCTION now_text() RETURNS TEXT LANGUAGE sql AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

-- A trigger that always refuses, with the message it is given. Used to keep tables append-only.
CREATE FUNCTION refuse() RETURNS trigger LANGUAGE plpgsql AS
$$ BEGIN RAISE EXCEPTION '%', TG_ARGV[0]; END $$;

-- After a build that loads rows with fixed ids (the seed), move every id counter past the highest id so the next insert gets a fresh one.
CREATE FUNCTION reset_sequences() RETURNS void LANGUAGE plpgsql AS
$$
DECLARE r record;
BEGIN
    FOR r IN SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public' AND is_identity = 'YES' LOOP
        EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE((SELECT MAX(%I) FROM %I), 0) + 1, false)',
                       r.table_name, r.column_name, r.column_name, r.table_name);
    END LOOP;
END
$$;

-- Controlled list of job titles, grouped into job families. Editable by admin/superuser.
CREATE TABLE role (
    role_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_code  TEXT NOT NULL UNIQUE,               -- e.g. PM-04
    name        TEXT NOT NULL UNIQUE,               -- job title
    family      TEXT NOT NULL,                      -- job family, e.g. Project Management
    active      INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0,1))
);

-- Where hours are worked (an hour type). Managed by the IT admin; location 1 (On site) is the default for new entries.
CREATE TABLE location (
    location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    active      INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    earns_allowance INTEGER NOT NULL DEFAULT 0 CHECK (earns_allowance IN (0,1))  -- 1 = a night here earns the allowance (Offshore)
);

-- Who can access / enter time.
CREATE TABLE app_user (
    user_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nmc_id          TEXT NOT NULL UNIQUE,            -- e.g. A001
    employment_type TEXT NOT NULL CHECK (employment_type IN ('Staff','Contractor - LTD','Contractor - PAYE')),
    name            TEXT NOT NULL,
    role_id         INTEGER NOT NULL REFERENCES role(role_id),
    permission      TEXT NOT NULL DEFAULT 'user' CHECK (permission IN ('user','controller','admin')),
    start_date      TEXT NOT NULL,
    end_date        TEXT,
    line_manager_id INTEGER REFERENCES app_user(user_id) CHECK (line_manager_id IS NULL OR line_manager_id <> user_id),
    -- Who approves this person's whole timesheet: the approver named here, otherwise their line manager (see v_person_approver). The approver is for when
    -- someone else makes more sense, for example a line manager who only works on one client approving someone working on another's scopes. When neither
    -- is set, a cost controller approves.
    approver_id     INTEGER REFERENCES app_user(user_id) CHECK (approver_id IS NULL OR approver_id <> user_id),
    -- Where this person normally works: new timesheet rows start with it. On Shore for most people, Offshore for an offshore rep, say.
    default_location_id INTEGER NOT NULL DEFAULT 1 REFERENCES location(location_id),
    -- Contracted hours a week. Hours booked above it are the overtime of the future (v_weekly_hours); the overtime flag itself is no longer used.
    hours_per_week  NUMERIC NOT NULL DEFAULT 40 CHECK (hours_per_week > 0 AND hours_per_week <= 168),
    -- Sign-in with Microsoft (Entra ID). Who a person is comes from Microsoft; what they may do stays here (permission, dates). Someone with no
    -- row here cannot sign in. entra_object_id is the stable key (it never changes, unlike names and addresses); it is filled from the
    -- tenant's user export, or on a first sign-in that matches by email. The password is never stored here.
    -- The email is kept in lower case, so one address is one person whatever capitals it was typed with.
    email           TEXT UNIQUE CHECK (email IS NULL OR (email LIKE '%_@_%' AND email NOT LIKE '% %' AND email = lower(email))),
    entra_object_id TEXT UNIQUE CHECK (entra_object_id IS NULL OR length(entra_object_id) = 36),
    last_login_at   TEXT,
    -- 0 = this person does not write time (a director, say): no timesheet, never chased for one, and the database refuses hours booked to them.
    books_time      INTEGER NOT NULL DEFAULT 1 CHECK (books_time IN (0,1))
);

-- Changes to people (who was added, and each change to a person's email, permission, role, dates, line manager, whether they write time, or the
-- Microsoft account linked to them). changed_by is empty when the system did it (the user import, or a first sign-in linking an account).
-- Append-only, like the time entry audit. The values are kept as readable text, so they still make sense after a role or person is renamed.
CREATE TABLE user_audit (
    audit_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES app_user(user_id),
    changed_by INTEGER REFERENCES app_user(user_id),
    changed_at TEXT NOT NULL DEFAULT now_text(),
    action     TEXT NOT NULL CHECK (action IN ('ADD','CHANGE')),
    field      TEXT NOT NULL,
    old_value  TEXT,
    new_value  TEXT
);
CREATE TRIGGER trg_user_audit_no_update BEFORE UPDATE ON user_audit FOR EACH ROW EXECUTE FUNCTION refuse('The user audit trail cannot be changed');
CREATE TRIGGER trg_user_audit_no_delete BEFORE DELETE ON user_audit FOR EACH ROW EXECUTE FUNCTION refuse('The user audit trail cannot be changed');

-- is_internal = 1 marks NMC's own "Internal" client: hours booked to its codes are paid by NMC, not billed to a client.
-- They have no rate, and are left out of the client CTR and period reports.
CREATE TABLE client (
    client_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    is_internal INTEGER NOT NULL DEFAULT 0 CHECK (is_internal IN (0,1)),
    framework_ref TEXT                                      -- framework agreement / contract reference, shown on each CTR sheet
);

-- Client rate card: one row per client + role + effective date.
CREATE TABLE rate (
    rate_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id      INTEGER NOT NULL REFERENCES client(client_id),
    role_id        INTEGER NOT NULL REFERENCES role(role_id),
    sales_rate     NUMERIC NOT NULL CHECK (sales_rate >= 0),
    effective_from TEXT NOT NULL DEFAULT '2026-01-01',
    UNIQUE (client_id, role_id, effective_from)
);

-- Hierarchy: client > project > scope > phase. Hours are booked to a phase (the lowest level). A phase is the CTR (the booking code).
CREATE TABLE project (
    project_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code  TEXT NOT NULL UNIQUE,
    name          TEXT NOT NULL,
    client_id     INTEGER NOT NULL REFERENCES client(client_id),
    status        TEXT NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Closed'))
);

CREATE TABLE scope (
    scope_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_code        TEXT NOT NULL UNIQUE,           -- e.g. BB0001
    client_id         INTEGER NOT NULL REFERENCES client(client_id),
    project_id        INTEGER NOT NULL REFERENCES project(project_id),
    description       TEXT NOT NULL,
    status            TEXT NOT NULL CHECK (status IN ('Pipeline','Open','Closed'))
);

-- A scope is split into phases (e.g. Define, Execute). Every scope has at least one.
CREATE TABLE phase (
    phase_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_id   INTEGER NOT NULL REFERENCES scope(scope_id),
    name       TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Closed')),
    description TEXT,                                   -- the CTR title
    -- The CTR sheet. The CTR number shown is the scope code plus ctr_code, e.g. A1500-PM-D-001 (discipline - phase letter - sequence).
    ctr_code   TEXT,
    objectives TEXT,
    inputs     TEXT,                                    -- input requirements
    scope_of_work TEXT,
    assumptions TEXT,
    exclusions TEXT,
    prepared_by TEXT,
    checked_by TEXT,
    expenses   TEXT NOT NULL DEFAULT 'Reimbursable',
    -- Non-reimbursable CTRs are left out of the billing extracts. A Lump Sum CTR works as a budget in money: lump_sum_value is the price
    -- agreed with the client, and the % billed is worked out when it is needed, not stored.
    payment_terms TEXT NOT NULL DEFAULT 'Reimbursable' CHECK (payment_terms IN ('Reimbursable','Budget','Lump Sum','Non-reimbursable')),
    lump_sum_value NUMERIC CHECK (lump_sum_value IS NULL OR (lump_sum_value >= 0 AND payment_terms = 'Lump Sum')),
    basis      TEXT,                                    -- basis of proposal
    wbs        TEXT,                                    -- optional WBS / CBS / ABS references
    cbs        TEXT,
    abs_code   TEXT,
    -- Transaction controls. restricted = 0: anyone can book to the code. restricted = 1: only the people listed in phase_person.
    -- book_from / book_to (both optional) limit the work dates that can be booked.
    restricted INTEGER NOT NULL DEFAULT 0 CHECK (restricted IN (0,1)),
    book_from  TEXT,
    book_to    TEXT,
    UNIQUE (scope_id, name),
    UNIQUE (scope_id, ctr_code)
);

-- People allowed to book to a restricted booking code.
CREATE TABLE phase_person (
    phase_id INTEGER NOT NULL REFERENCES phase(phase_id),
    user_id  INTEGER NOT NULL REFERENCES app_user(user_id),
    PRIMARY KEY (phase_id, user_id)
);

-- Who approves whom: each person's timesheet goes to their approver if one is named, otherwise to their line manager. Someone with neither has no
-- approver, and a cost controller approves their hours.
CREATE VIEW v_person_approver AS
SELECT user_id, COALESCE(approver_id, line_manager_id) AS approver_id FROM app_user WHERE COALESCE(approver_id, line_manager_id) IS NOT NULL;

-- A scope sits under a project of the same client.
CREATE FUNCTION f_scope_project_client() RETURNS trigger LANGUAGE plpgsql AS
$$
BEGIN
    IF (SELECT client_id FROM project WHERE project_id = NEW.project_id) <> NEW.client_id THEN
        RAISE EXCEPTION 'The scope client must match its project client';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_scope_project_client_insert BEFORE INSERT ON scope FOR EACH ROW EXECUTE FUNCTION f_scope_project_client();
CREATE TRIGGER trg_scope_project_client_update BEFORE UPDATE OF client_id, project_id ON scope FOR EACH ROW EXECUTE FUNCTION f_scope_project_client();

-- Rates are append-only so past billing stays reproducible: a change is a new row with a later effective date.
CREATE TRIGGER trg_rate_no_update BEFORE UPDATE ON rate FOR EACH ROW EXECUTE FUNCTION refuse('Rates are never edited: add a new row with a later effective date');
CREATE TRIGGER trg_rate_no_delete BEFORE DELETE ON rate FOR EACH ROW EXECUTE FUNCTION refuse('Rates are never deleted: add a new row with a later effective date');

-- The internal client has no rate card.
CREATE FUNCTION f_rate_not_internal() RETURNS trigger LANGUAGE plpgsql AS
$$
BEGIN
    IF (SELECT is_internal FROM client WHERE client_id = NEW.client_id) = 1 THEN
        RAISE EXCEPTION 'Internal codes have no rate card';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_rate_not_internal BEFORE INSERT ON rate FOR EACH ROW EXECUTE FUNCTION f_rate_not_internal();

-- Weekly periods (Mon-Sun), identified by the Monday. An entry's week is derived from work_date.
-- The app opens the current week automatically; admin can still open a missed week or close a week.
CREATE TABLE period (
    week_start  TEXT PRIMARY KEY CHECK (CASE WHEN week_start ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN extract(isodow FROM week_start::date) = 1 ELSE false END),
    status      TEXT NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Closed')),
    closed_by   INTEGER REFERENCES app_user(user_id),
    closed_at   TEXT
);

-- Lifecycle: Draft -> Submitted -> Approved. Reject sends Submitted back to Draft (reason stored).
-- Editing an Approved entry makes it Edited (reason required) and it needs re-approval.
CREATE TABLE time_entry (
    entry_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES app_user(user_id),
    scope_id    INTEGER NOT NULL REFERENCES scope(scope_id),
    phase_id    INTEGER NOT NULL REFERENCES phase(phase_id), -- lowest booking level; must belong to scope_id
    worked_role_id INTEGER NOT NULL REFERENCES role(role_id), -- skill code booked under (defaults to user's role)
    rate_id     INTEGER REFERENCES rate(rate_id),            -- client sales rate for worked role, snapshot at booking; NULL for internal hours
    work_date   TEXT NOT NULL,
    hours       NUMERIC NOT NULL CHECK (hours > 0 AND hours <= 24),
    location_id INTEGER NOT NULL DEFAULT 1 REFERENCES location(location_id),  -- where the hours were worked
    overtime    INTEGER NOT NULL DEFAULT 0 CHECK (overtime IN (0,1)),         -- 1 = an overtime line (no separate rate yet)
    status      TEXT NOT NULL DEFAULT 'Submitted' CHECK (status IN ('Draft','Submitted','Approved','Edited')),
    approved_by INTEGER REFERENCES app_user(user_id),
    approved_at TEXT,
    reject_reason      TEXT,                          -- set when sent back to Draft
    reopen_reason      TEXT,                          -- set when a cost controller reopens submitted or approved hours
    last_change_reason TEXT,                          -- required for controlled edits
    edit_count  INTEGER NOT NULL DEFAULT 0,           -- times edited after approval
    created_by     INTEGER NOT NULL REFERENCES app_user(user_id),  -- who keyed it (may differ from user_id)
    created_at     TEXT NOT NULL DEFAULT now_text(),
    last_edited_by INTEGER REFERENCES app_user(user_id),
    last_edited_at TEXT
);
CREATE INDEX ix_time_entry_user_date ON time_entry (user_id, work_date);
CREATE INDEX ix_time_entry_scope ON time_entry (scope_id);
CREATE INDEX ix_time_entry_phase ON time_entry (phase_id);
CREATE INDEX ix_time_entry_status ON time_entry (status);

-- Audit event for every create, edit, status change and deletion of a Draft.
CREATE TABLE time_entry_audit (
    audit_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    INTEGER NOT NULL,
    action      TEXT NOT NULL CHECK (action IN ('CREATE','UPDATE','STATUS','DELETE')),
    changed_by  INTEGER REFERENCES app_user(user_id),
    changed_at  TEXT NOT NULL DEFAULT now_text(),
    reason      TEXT,
    old_status  TEXT, new_status TEXT,
    old_hours   NUMERIC, new_hours NUMERIC,
    old_scope_id INTEGER, old_phase_id INTEGER, old_worked_role_id INTEGER, old_rate_id INTEGER, old_work_date TEXT,
    old_location_id INTEGER, old_overtime INTEGER
);
CREATE INDEX ix_time_entry_audit_entry ON time_entry_audit (entry_id);

-- Booking guard: Open scope, matching rate for the client, Open weekly period.
-- (Triggers on one event run in the order of their names, so the numbers 1_ and 2_ keep them in the order the checks were written.)
CREATE FUNCTION f_time_entry_valid() RETURNS trigger LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.status NOT IN ('Draft','Submitted') THEN
        RAISE EXCEPTION 'New entries must be Draft or Submitted';
    END IF;
    -- Only people who are live can book: the work date must fall within their start and end dates (no end date = still employed).
    IF EXISTS (SELECT 1 FROM app_user
               WHERE user_id = NEW.user_id AND (NEW.work_date < start_date OR (end_date IS NOT NULL AND NEW.work_date > end_date))) THEN
        RAISE EXCEPTION 'This person is not active on that date (check their start and end dates)';
    END IF;
    IF EXISTS (SELECT 1 FROM app_user WHERE user_id = NEW.user_id AND books_time = 0) THEN
        RAISE EXCEPTION 'This person does not write time';
    END IF;
    IF (SELECT status FROM scope WHERE scope_id = NEW.scope_id) <> 'Open' THEN
        RAISE EXCEPTION 'Scope is not Open';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM phase WHERE phase_id = NEW.phase_id AND scope_id = NEW.scope_id) THEN
        RAISE EXCEPTION 'CTR does not belong to this scope';
    END IF;
    IF (SELECT pr.status FROM scope sc JOIN project pr ON pr.project_id = sc.project_id WHERE sc.scope_id = NEW.scope_id) <> 'Open' THEN
        RAISE EXCEPTION 'Project is not Open';
    END IF;
    IF (SELECT status FROM phase WHERE phase_id = NEW.phase_id) <> 'Open' THEN
        RAISE EXCEPTION 'CTR is not Open';
    END IF;
    -- Transaction controls on the booking code: a list of people, and a window of dates (both optional).
    IF (SELECT restricted FROM phase WHERE phase_id = NEW.phase_id) = 1
       AND NOT EXISTS (SELECT 1 FROM phase_person WHERE phase_id = NEW.phase_id AND user_id = NEW.user_id) THEN
        RAISE EXCEPTION 'This booking code is restricted and this person is not on its list of people';
    END IF;
    IF EXISTS (SELECT 1 FROM phase WHERE phase_id = NEW.phase_id
               AND ((book_from IS NOT NULL AND NEW.work_date < book_from) OR (book_to IS NOT NULL AND NEW.work_date > book_to))) THEN
        RAISE EXCEPTION 'This booking code cannot be booked on that date (outside its booking dates)';
    END IF;
    -- Client work needs the client's rate for the skill code booked. Internal hours have no rate.
    IF (SELECT c.is_internal FROM scope sc JOIN client c ON c.client_id = sc.client_id WHERE sc.scope_id = NEW.scope_id) = 0
       AND NOT EXISTS (
         SELECT 1 FROM rate r JOIN scope s ON s.client_id = r.client_id
         WHERE r.rate_id = NEW.rate_id AND s.scope_id = NEW.scope_id AND r.role_id = NEW.worked_role_id) THEN
        RAISE EXCEPTION 'Rate does not match the scope client and worked role';
    END IF;
    IF (SELECT c.is_internal FROM scope sc JOIN client c ON c.client_id = sc.client_id WHERE sc.scope_id = NEW.scope_id) = 1
       AND NEW.rate_id IS NOT NULL THEN
        RAISE EXCEPTION 'Internal hours have no rate';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM period WHERE week_start = monday_of(NEW.work_date) AND status = 'Open') THEN
        RAISE EXCEPTION 'Weekly period is not open';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_time_entry_1_valid BEFORE INSERT ON time_entry FOR EACH ROW EXECUTE FUNCTION f_time_entry_valid();

-- One person cannot book more than 24 hours on one day, however many rows (codes, locations, overtime) the hours are spread over.
CREATE FUNCTION f_time_entry_day_cap() RETURNS trigger LANGUAGE plpgsql AS
$$
BEGIN
    IF COALESCE((SELECT SUM(hours) FROM time_entry
                 WHERE user_id = NEW.user_id AND work_date = NEW.work_date AND (TG_OP = 'INSERT' OR entry_id <> NEW.entry_id)), 0) + NEW.hours > 24 THEN
        RAISE EXCEPTION 'A person cannot book more than 24 hours in one day';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_time_entry_2_day_cap_insert BEFORE INSERT ON time_entry FOR EACH ROW EXECUTE FUNCTION f_time_entry_day_cap();
CREATE TRIGGER trg_time_entry_2_day_cap_update BEFORE UPDATE OF hours, work_date ON time_entry FOR EACH ROW EXECUTE FUNCTION f_time_entry_day_cap();

-- Edit rules.
CREATE FUNCTION f_time_entry_edit_rules() RETURNS trigger LANGUAGE plpgsql AS
$$
BEGIN
    -- no anonymous changes
    IF NEW.last_edited_by IS NULL OR NEW.last_edited_at IS NULL
       OR (NEW.last_edited_by IS NOT DISTINCT FROM OLD.last_edited_by AND NEW.last_edited_at IS NOT DISTINCT FROM OLD.last_edited_at) THEN
        RAISE EXCEPTION 'Edits must set last_edited_by and last_edited_at';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM phase WHERE phase_id = NEW.phase_id AND scope_id = NEW.scope_id) THEN
        RAISE EXCEPTION 'CTR does not belong to this scope';
    END IF;

    -- changing an approved entry makes it Edited
    IF OLD.status IN ('Approved','Edited') AND NEW.status <> 'Edited'
       AND (NEW.hours IS DISTINCT FROM OLD.hours OR NEW.scope_id IS DISTINCT FROM OLD.scope_id OR NEW.phase_id IS DISTINCT FROM OLD.phase_id
            OR NEW.work_date IS DISTINCT FROM OLD.work_date OR NEW.worked_role_id IS DISTINCT FROM OLD.worked_role_id
            OR NEW.rate_id IS DISTINCT FROM OLD.rate_id OR NEW.location_id IS DISTINCT FROM OLD.location_id
            OR NEW.overtime IS DISTINCT FROM OLD.overtime OR NEW.user_id IS DISTINCT FROM OLD.user_id)
       AND NOT (OLD.status = 'Edited' AND NEW.status = 'Approved') THEN
        RAISE EXCEPTION 'Changing an approved entry sets its status to Edited';
    END IF;

    -- controlled edits need a reason
    IF NEW.status = 'Edited' AND OLD.status IN ('Approved','Edited')
       AND (NEW.last_change_reason IS NULL OR NEW.last_change_reason = '' OR NEW.last_change_reason IS NOT DISTINCT FROM OLD.last_change_reason) THEN
        RAISE EXCEPTION 'A controlled edit needs a reason (last_change_reason)';
    END IF;

    -- reject (Submitted -> Draft) needs a reason: a reject_reason, or a reopen_reason when a cost controller reopens it
    IF OLD.status = 'Submitted' AND NEW.status = 'Draft'
       AND (NEW.reject_reason IS NULL OR NEW.reject_reason = '')
       AND (NEW.reopen_reason IS NULL OR NEW.reopen_reason = '' OR NEW.reopen_reason IS NOT DISTINCT FROM OLD.reopen_reason) THEN
        RAISE EXCEPTION 'Rejecting an entry needs a reason (reject_reason)';
    END IF;

    -- reopen: only a cost controller can send submitted or approved hours back to Draft, and only with a reason
    IF NEW.status = 'Draft' AND OLD.status IN ('Approved','Edited')
       AND (NEW.reopen_reason IS NULL OR NEW.reopen_reason = '' OR NEW.reopen_reason IS NOT DISTINCT FROM OLD.reopen_reason
            OR (SELECT permission FROM app_user WHERE user_id = NEW.last_edited_by) <> 'controller') THEN
        RAISE EXCEPTION 'Only a cost controller can reopen submitted or approved hours, and they must give a reason (reopen_reason)';
    END IF;
    IF NEW.status = 'Draft' AND OLD.status = 'Submitted'
       AND NEW.reopen_reason IS NOT NULL AND NEW.reopen_reason IS DISTINCT FROM OLD.reopen_reason
       AND (SELECT permission FROM app_user WHERE user_id = NEW.last_edited_by) <> 'controller' THEN
        RAISE EXCEPTION 'Only a cost controller can reopen submitted hours';
    END IF;
    IF NEW.status = 'Draft' AND OLD.status <> 'Draft'
       AND NEW.reopen_reason IS NOT NULL AND NEW.reopen_reason IS DISTINCT FROM OLD.reopen_reason
       AND NEW.last_edited_by = NEW.user_id THEN
        RAISE EXCEPTION 'A cost controller cannot reopen their own hours';
    END IF;

    -- approval: the person's approver (the approver named on their record, otherwise their line manager), never the entry owner. Someone with neither has
    -- nobody to approve for them, so a cost controller approves those hours.
    IF NEW.status = 'Approved' AND OLD.status <> 'Approved'
       AND (NEW.approved_by IS NULL
            OR NEW.approved_by = NEW.user_id
            OR NOT (
                 EXISTS (SELECT 1 FROM v_person_approver WHERE user_id = NEW.user_id AND approver_id = NEW.approved_by)
                 OR
                 ((SELECT permission FROM app_user WHERE user_id = NEW.approved_by) = 'controller'
                  AND NOT EXISTS (SELECT 1 FROM v_person_approver WHERE user_id = NEW.user_id)))) THEN
        RAISE EXCEPTION 'Only this person''s approver (their line manager, or the approver named on their record) can approve their hours, and never your own; a cost controller approves when nobody is set';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_time_entry_1_edit_rules BEFORE UPDATE ON time_entry FOR EACH ROW EXECUTE FUNCTION f_time_entry_edit_rules();

